master = master.merge(job_skl, on='job_id', how='left')
master['total_skills'] = master['total_skills'].fillna(0)
master = master.merge(job_ind[['job_id','industry_name']], on='job_id', how='left')
master['company_size'] = pd.to_numeric(master['company_size'], errors='coerce')
master['description'] = master['description'].fillna('').astype(str)
