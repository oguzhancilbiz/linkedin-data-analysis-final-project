print(f"Q1 (25. yuzdelik)   : ${q1:>12,.0f}")
print(f"Q3 (75. yuzdelik)   : ${q3:>12,.0f}")
print(f"IQR (Q3 - Q1)       : ${iqr:>12,.0f}")
print(f"Alt sinir (Q1-1.5x) : ${lo_iqr:>12,.0f}  <- negatif, pratikte $0 alti yok")
print(f"Ust sinir (Q3+1.5x) : ${hi_iqr:>12,.0f}")
print(f"Ayiklanan           : {len(s_raw)-len(s_iqr):,}  (%{(len(s_raw)-len(s_iqr))/len(s_raw)*100:.2f})")
print(f"Temiz medyan        : ${s_iqr.median():,.0f}  |  Temiz mean: ${s_iqr.mean():,.0f}")

"""### 💡 Kod Açıklaması
`quantile([0.25, 0.75])` tek çağrıda Q1 ve Q3'ü döndürür. Boolean mask ile sınır içindeki değerler seçilir. Sınır dışındakiler aykırı sayılır — satırlar silinmez, maaş hücresi NaN yapılır.

### Yöntem 2 — Z-Score (|z| > 3)

**Ne yapar?** Her değerin ortalamadan kaç standart sapma uzak olduğunu ölçer.
`z = (x − μ) / σ`. Mutlak değeri 3'ü geçen değerler aykırı sayılır.

**Neden bu veride riskli?**
Maaş normal değil — sağa çarpık. $535M'lık tek hata ortalamayı ve std'yi o kadar şişirir ki
gerçek yüksek maaşlar ($200K) da "normal" görünebilir. Hata içeride kalabilir.
"""

from scipy import stats

z_scores = np.abs(stats.zscore(s_raw))
s_zscore = s_raw[z_scores < 3]

print(f"Ham ortalama  : ${s_raw.mean():>12,.0f}  <- 535M$ tarafindan yukari cekilmis!")
print(f"Ham std       : ${s_raw.std():>12,.0f}  <- cok buyuk, anlamsiz")
print(f"Ayiklanan     : {len(s_raw)-len(s_zscore):,}  (%{(len(s_raw)-len(s_zscore))/len(s_raw)*100:.2f})")
print(f"Temiz max     : ${s_zscore.max():>12,.0f}  <- $6.9M icerde kaldi!")
print(f"Temiz medyan  : ${s_zscore.median():,.0f}  |  Temiz mean: ${s_zscore.mean():,.0f}")
print()
print("SORUN: Z-Score yalnizca 28 deger ayikladi.")
print("$6.9M'lik deger icerde kaldi — bu ciddi bir basarisizlik.")
print("Sebep: carpik veride mean+std'yi outlier'lar kendisi bozuyor.")

"""### 💡 Kod Açıklaması
`stats.zscore()` her değer için z skorunu döndürür. `np.abs()` pozitif/negatif sapmayı birleştirir. **Bu veride güvenilmez:** ortalama ve standart sapma, tespit etmeye çalıştığımız aykırı değerlerin kendisi tarafından bozuluyor.

### 📊 Yorum
Z-Score yalnızca 28 değer ayıkladı; en büyük hata $535M yakalandı ama $6.9M'lık değer içeride kaldı. Çarpık veride **kullanılmamalı**.

### Yöntem 3 — Modified Z-Score (MAD Tabanlı)

**Ne yapar?** Z-Score'un ortalama/std yerine **medyan ve MAD** (Median Absolute Deviation)
kullandığı versiyonu. `M_z = 0.6745 × (x − median) / MAD`.
Iglewicz & Hoaglin (1993) |M_z| > 3.5 eşiğini önerir.

**Neden daha iyi?** Medyan aykırı değerlerden etkilenmez — Z-Score'un temel zaafiyeti giderilmiş.
<br>**IQR'dan farkı?** IQR iki nokta (Q1, Q3) kullanır; Modified Z-Score tüm veriyi
medyan etrafında değerlendirir. Sonuçlar genellikle çok yakın.
"""

median_s = s_raw.median()
mad      = np.median(np.abs(s_raw - median_s))
mod_z    = 0.6745 * (s_raw - median_s) / mad
s_mz     = s_raw[np.abs(mod_z) < 3.5]

print(f"Medyan        : ${median_s:>12,.0f}")
print(f"MAD           : ${mad:>12,.0f}")
print(f"Ayiklanan     : {len(s_raw)-len(s_mz):,}  (%{(len(s_raw)-len(s_mz))/len(s_raw)*100:.2f})")
print(f"Temiz max     : ${s_mz.max():>12,.0f}  <- IQR'in $234.5K'sindan biraz yuksek")
print(f"Temiz medyan  : ${s_mz.median():,.0f}  |  Temiz mean: ${s_mz.mean():,.0f}")

"""### 📊 Yorum
Modified Z-Score (683 aykırı) IQR'dan (952) biraz daha az agresif. Temiz max $257K — bu makul. **Kabul edilebilir alternatif** — ama bu veride IQR'dan anlamlı bir fark yok.

### Yöntem 4 — Winsorize / Capping (P1–P99)

**Ne yapar?** Aykırı değerleri **silmek yerine** en yakın geçerli sınır değeriyle **değiştirir**.
P1 altındaki her değer → P1 değerine, P99 üstü → P99 değerine çekilir.
**Veri kaybı yoktur** — tüm satırlar korunur.

**Ne zaman idealdir?** A/B testleri, finans verisi, gelir analizlerinde standarttır.
"Silemem ama 535M'ı da kabul edemem" durumunda doğal seçim.
"""

p1, p99  = s_raw.quantile([0.01, 0.99])
s_winsor = s_raw.clip(lower=p1, upper=p99)

