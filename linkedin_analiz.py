print(f"Eski max      : ${s_raw.max():>12,.0f}  ->  Yeni max: ${s_winsor.max():,.0f}")
print(f"Temiz medyan  : ${s_winsor.median():,.0f}")
print(f"Temiz mean    : ${s_winsor.mean():,.0f}  (ham: ${s_raw.mean():,.0f})")
